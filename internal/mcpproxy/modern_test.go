// modernBackendHandler builds an httptest handler that responds to modern
// (2026-07-28) JSON-RPC POST requests. It dispatches on the Mcp-Method header
// and returns a per-backend result generated by respFn, wrapped as a JSON-RPC
// success response. Backends listed in failBackends return a 500 so partial
// failure handling can be exercised.
func modernBackendHandler(t *testing.T, callCount *perBackendCallCount, failBackends map[string]bool, respFn func(backend, method string) any) http.Handler {
	t.Helper()
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		backend := r.Header.Get(internalapi.MCPBackendHeader)
		require.NotEmpty(t, backend, "backend header must be set on modern outbound request")
		method := r.Header.Get(mcpMethodHeader)
		require.Equal(t, protocolVersion20260728, r.Header.Get(mcpProtocolVersionHeader))
		if callCount != nil {
			callCount.inc(backend)
		}
		if failBackends[backend] {
			w.WriteHeader(http.StatusInternalServerError)
			_, _ = w.Write([]byte("backend down"))
			return
		}
		result := respFn(backend, method)
		var id any = 1
		body := map[string]any{"jsonrpc": "2.0", "id": id, "result": result}
		encoded, err := json.Marshal(body)
		require.NoError(t, err)
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write(encoded)
	})
}

// newModernRequest builds an *http.Request carrying the modern headers that
// serveModernPOST validates before dispatching.
func newModernRequest(method string) *http.Request {
	r := httptest.NewRequest(http.MethodPost, "/mcp", nil)
	r.Header.Set(internalapi.MCPRouteHeader, "test-route")
	r.Header.Set(mcpMethodHeader, method)
	r.Header.Set(mcpProtocolVersionHeader, protocolVersion20260728)
	return r
}

func modernReq(t *testing.T, method string, params []byte) *jsonrpc.Request {
	t.Helper()
	id, err := jsonrpc.MakeID("1")
	require.NoError(t, err)
	return &jsonrpc.Request{ID: id, Method: method, Params: params}
}

// decodeResult decodes the JSON-RPC "result" object from a recorded response.
func decodeResult(t *testing.T, rr *httptest.ResponseRecorder) map[string]json.RawMessage {
	t.Helper()
	var envelope map[string]json.RawMessage
	require.NoError(t, json.Unmarshal(rr.Body.Bytes(), &envelope))
	require.Contains(t, envelope, "result")
	var result map[string]json.RawMessage
	require.NoError(t, json.Unmarshal(envelope["result"], &result))
	return result
}

