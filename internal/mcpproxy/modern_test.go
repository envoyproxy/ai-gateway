// TestServeModernPOST_DispatchFanout drives each fan-out method end-to-end
// through serveModernPOST against a live backend server.
func TestServeModernPOST_DispatchFanout(t *testing.T) {
	respFn := func(backend, method string) any {
		switch method {
		case "server/discover":
			return mcp.DiscoverResult{SupportedVersions: supportedVersions, Capabilities: &mcp.ServerCapabilities{}}
		case "tools/list":
			return mcp.ListToolsResult{Tools: []*mcp.Tool{{Name: "t-" + backend}}}
		case "resources/list":
			return mcp.ListResourcesResult{Resources: []*mcp.Resource{{Name: "r-" + backend, URI: "file:///" + backend}}}
		case "resources/templates/list":
			return mcp.ListResourceTemplatesResult{ResourceTemplates: []*mcp.ResourceTemplate{{Name: "rt-" + backend, URITemplate: "file:///{x}"}}}
		case "prompts/list":
			return mcp.ListPromptsResult{Prompts: []*mcp.Prompt{{Name: "p-" + backend}}}
		}
		return map[string]any{}
	}

	for _, method := range []string{"server/discover", "tools/list", "resources/list", "resources/templates/list", "prompts/list"} {
		t.Run(method, func(t *testing.T) {
			server := httptest.NewServer(modernBackendHandler(t, nil, nil, respFn))
			defer server.Close()

			proxy := newTestMCPProxy()
			proxy.backendListenerAddr = server.URL
			// test-route has no tool selectors on backend2, but backend1 restricts to "test-tool".
			delete(proxy.routes["test-route"].toolSelectors, "backend1")

			r := newModernRequest(method)
			rr := httptest.NewRecorder()
			req := modernReq(t, method, nil)

			proxy.serveModernPOST(rr, r, req, time.Now())

			require.Equal(t, http.StatusOK, rr.Code, rr.Body.String())
			result := decodeResult(t, rr)
			require.Equal(t, `"complete"`, string(result["resultType"]))
			require.True(t, proxy.perBackendMetricsRecorded)
		})
	}
}

