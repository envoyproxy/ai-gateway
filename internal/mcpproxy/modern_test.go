func TestEnsureResultType(t *testing.T) {
	require.JSONEq(t, `{"resultType":"complete"}`, string(ensureResultType(nil)))
	require.JSONEq(t, `{"resultType":"complete","x":1}`, string(ensureResultType([]byte(`{"x":1}`))))
	// Already has resultType: left untouched.
	require.JSONEq(t, `{"resultType":"input_required"}`, string(ensureResultType([]byte(`{"resultType":"input_required"}`))))
	// Non-object JSON: returned as-is.
	require.Equal(t, `123`, string(ensureResultType([]byte(`123`))))
}

func TestWriteJSONRPCResult(t *testing.T) {
	rr := httptest.NewRecorder()
	id, err := jsonrpc.MakeID("42")
	require.NoError(t, err)
	writeJSONRPCResult(rr, id, map[string]any{"hello": "world"})

	require.Equal(t, http.StatusOK, rr.Code)
	require.Equal(t, "application/json", rr.Header().Get("Content-Type"))
	var envelope map[string]json.RawMessage
	require.NoError(t, json.Unmarshal(rr.Body.Bytes(), &envelope))
	require.Equal(t, `"2.0"`, string(envelope["jsonrpc"]))
	var result map[string]json.RawMessage
	require.NoError(t, json.Unmarshal(envelope["result"], &result))
	require.Equal(t, `"complete"`, string(result["resultType"]))
}

